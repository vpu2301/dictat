// Languages that lay out right-to-left. Used to flip `document.dir`.
export const RTL_LANGS = new Set(LANGS.filter((l) => l.rtl).map((l) => l.code));
export const isRtl = (lang) => RTL_LANGS.has(lang);

// Keyed-content picker for {uk, en, pl, …} objects with English fallback.
export const pickLang = (obj, lang) =>
  obj && typeof obj === "object" ? (obj[lang] ?? obj.en) : obj;

// Inline-ternary replacement for platform screens. Historic code wrote
// `lang === "uk" ? "укр" : "eng"`; tr() keeps uk/en verbatim and resolves the
// other languages from the EN-keyed dictionaries in src/translations/
// (English text is the lookup key; missing entries fall back to English).
import { PLATFORM_TR } from "./translations/platform.js";
export const tr = (lang, uk, en) => {
  if (lang === "uk") return uk;
  const d = PLATFORM_TR[lang];
  return (d && d[en]) || en;
};

